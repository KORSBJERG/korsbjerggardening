import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code=await readFile('worker/maps.js','utf8');
const gardens=[{id:'g1',name:'Have A',address:'Vej 1, 8420 Knebel',customer:'A',area:100,budget:5},{id:'g2',name:'Have B',address:'Anden vej 2, Aarhus',customer:'B'}];
const listeners={};
const context=vm.createContext({state:{gardens,tasks:[]},selectedGarden:'g1',customerMode:false,loaded:true,commerceBusy:false,attendanceBusy:false,mailBusy:false,document:{addEventListener:(event,handler)=>listeners[event]=handler},esc:s=>String(s).replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;'),heading:(...args)=>args.join(' '),section:()=>'',icon:()=>'',fmt:String,total:()=>0,taskRow:()=>'',modal:()=>{},render:()=>{}});
vm.runInContext(code,context);
const run=s=>vm.runInContext(s,context);
assert.equal(run('parseMapCoordinates("56.2, 10.4").lat'),56.2);
assert.equal(run('parseMapCoordinates("")'),null);
for(const bad of ['91,10','56,181','NaN,10','56,2,10,4','https://evil.test','1e3,2'])assert.throws(()=>run('parseMapCoordinates('+JSON.stringify(bad)+')'));
assert.match(run('gardenMap(state.gardens[0])'),/q=Vej%201%2C%208420%20Knebel/);
assert.match(run('gardenMap(state.gardens[0])'),/t=k/);
run('gardenMapLayer="street"');assert.match(run('gardenMap(state.gardens[0])'),/t=m/);
run('state.gardens[0].mapPosition={lat:56.2,lng:10.4,address:state.gardens[0].address}');
assert.equal(run('mapQuery(state.gardens[0])'),'56.2,10.4');
assert.match(run('mapLinks(state.gardens[0]).route'),/destination=56.2%2C10.4/);
run('state.gardens[0].address="Changed address"');assert.equal(run('mapQuery(state.gardens[0])'),'Changed address');
assert.match(run('gardenMap({name:"No address"})'),/Tilføj havens fulde adresse/);
run('selectedGarden="g2"');assert.match(run('mapSvg()'),/Anden%20vej/);
run('customerMode=true;state.gardens=state.gardens.filter(g=>g.id===selectedGarden)');const customer=run('mapPage()');assert(!customer.includes('data-map-edit'));assert(!customer.includes('Have A'));
run('state.gardens=[]');assert.match(run('mapPage()'),/Opret en have/);
const ui=await readFile('worker/ui.html','utf8'),front=await readFile('worker/front.html','utf8');
assert(!ui.includes('20764'));assert(!ui.includes('540 m²'));assert(!ui.includes('Illustrativt oversigtskort'));
assert(front.includes('title="Korsbjerg Gardening – Knebel og Djursland"'));assert(!front.includes('Skematisk områdeillustration'));
console.log('PASS: address-based maps; satellite/street layers; per-garden switching; coordinate validation; stale pins ignored; directions; missing addresses; customer edit restrictions; example map data removed.');
